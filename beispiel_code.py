#!/usr/bin/env python3

# Schleifen in Python

# for-Schleife: Iteration über eine Liste von Zahlen
zahlen = [1, 2, 3, 4, 5]
for zahl in zahlen:
  print("Zahl aus der Liste:",zahl)

# for-Schleife: Iteration über einen Bereich (range)
for i in range(1, 6):
  print("Aktueller Wert von i:",zahlen[(i-1)])